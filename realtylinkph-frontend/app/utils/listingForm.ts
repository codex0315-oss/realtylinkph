/** "₱5,000,000" or "₱25,000 / month"; a hint when no price is set. */
export function listingPriceText(price: number, offer: string): string {
  const n = Number(price)
  if (!(n > 0)) return 'Price not set'
  return `₱${n.toLocaleString('en-PH')}${offer === 'rent' ? ' / month' : ''}`
}
